const RED = [
  ['胸痛', '胸痛可能和心梗有关'],
  ['呼吸困难', '喘不上气很危险'],
  ['喘不上气', '喘不上气很危险'],
  ['憋气', '持续憋气很危险'],
  ['意识模糊', '意识不清要马上就医'],
  ['昏迷', '叫不醒要马上就医'],
  ['昏倒', '突然昏倒要马上就医'],
  ['抽搐', '抽搐要马上就医'],
  ['惊厥', '惊厥要马上就医'],
  ['大出血', '出血量大要马上就医'],
  ['血流不止', '血止不住要马上就医'],
  ['呕血', '吐血要马上就医'],
  ['吐鲜血', '吐血要马上就医'],
  ['咯血', '咳血要马上就医'],
  ['喷射', '喷射性呕吐很危险'],
  ['言语不清', '说话含糊，可能中风'],
  ['半身麻木', '半边身子没力，可能中风'],
  ['口角歪斜', '嘴歪了，可能中风'],
  ['刀割样', '刀割一样的剧痛要马上就医'],
  ['压榨', '胸口压榨感，可能心梗'],
  ['剧痛', '剧烈疼痛要马上就医'],
]

export function checkRed (text) {
  if (!text) return null
  for (const [kw, reason] of RED) {
    if (text.includes(kw)) return { level: 'red', reason }
  }
  return null
}
